-- HSHONAD game API additive migration
-- Run in Supabase SQL Editor before deploying handlers that read these tables.
-- This migration does not replace or recreate public.players.

create table if not exists public.game_bonus_data (
  id bigint generated by default as identity primary key,
  code text unique,
  title text not null default '',
  payload jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.game_mailbox (
  id bigint generated by default as identity primary key,
  steam_id text not null references public.players(steam_id) on delete cascade,
  title text not null default '',
  message text not null default '',
  attachments jsonb not null default '[]'::jsonb,
  claimed_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.game_gacha_banners (
  id bigint generated by default as identity primary key,
  banner_key text not null unique,
  title text not null default '',
  payload jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.game_treasure_progress (
  id bigint generated by default as identity primary key,
  steam_id text not null references public.players(steam_id) on delete cascade,
  treasure_key text not null,
  progress jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  unique (steam_id, treasure_key)
);

create index if not exists game_mailbox_steam_created_idx
  on public.game_mailbox (steam_id, created_at desc);
create index if not exists game_mailbox_expiry_idx
  on public.game_mailbox (expires_at) where expires_at is not null;
create index if not exists game_bonus_active_dates_idx
  on public.game_bonus_data (is_active, starts_at, ends_at);
create index if not exists game_gacha_active_dates_idx
  on public.game_gacha_banners (is_active, starts_at, ends_at);
create index if not exists game_treasure_steam_idx
  on public.game_treasure_progress (steam_id);

alter table public.game_bonus_data enable row level security;
alter table public.game_mailbox enable row level security;
alter table public.game_gacha_banners enable row level security;
alter table public.game_treasure_progress enable row level security;

revoke all on public.game_bonus_data from anon, authenticated;
revoke all on public.game_mailbox from anon, authenticated;
revoke all on public.game_gacha_banners from anon, authenticated;
revoke all on public.game_treasure_progress from anon, authenticated;

grant all on public.game_bonus_data to service_role;
grant all on public.game_mailbox to service_role;
grant all on public.game_gacha_banners to service_role;
grant all on public.game_treasure_progress to service_role;

-- Identity columns use sequences; grant service_role the required sequence access.
grant usage, select on all sequences in schema public to service_role;
