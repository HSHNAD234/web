-- Hosts Registry for HSHONAD Launcher. Additive: does not alter player tables.
create table if not exists public.host_registry (
  domain text primary key check (domain in (
    'api.homesweethomegame.com',
    'hshsapi.homesweethomegame.com',
    'logapi.homesweethomegame.com',
    'boatltpk'
  )),
  enabled boolean not null default false,
  purpose text not null default '' check (char_length(purpose) <= 120),
  note text not null default '' check (char_length(note) <= 160),
  updated_at timestamptz not null default now()
);

create table if not exists public.host_registry_audit (
  id bigint generated by default as identity primary key,
  changed_at timestamptz not null default now(),
  actor text not null default 'admin',
  before_state jsonb not null,
  after_state jsonb not null
);

