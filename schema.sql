create or replace function public.save_host_registry(p_hosts jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  item jsonb;
  host_domain text;
  purpose_value text;
  note_value text;
  before_state jsonb;
  after_state jsonb;
begin
  if p_hosts is null
     or pg_catalog.jsonb_typeof(p_hosts) <> 'array'
     or pg_catalog.jsonb_array_length(p_hosts) <> 4 then
    raise exception 'hosts must contain exactly four domains';
  end if;

  if (
    select count(distinct elem.value->>'domain')
    from pg_catalog.jsonb_array_elements(p_hosts) as elem(value)
  ) <> 4 then
    raise exception 'each domain must appear exactly once';
  end if;

  select coalesce(
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'domain', h.domain,
        'enabled', h.enabled,
        'purpose', h.purpose,
        'note', h.note,
        'updatedAt', h.updated_at
      )
      order by pg_catalog.array_position(
        array[
          'api.homesweethomegame.com',
          'hshsapi.homesweethomegame.com',
          'logapi.homesweethomegame.com',
          'boatltpk'
        ]::text[],
        h.domain
      )
    ),
    '[]'::jsonb
  )
  into before_state
  from public.host_registry as h;

  for item in
    select value from pg_catalog.jsonb_array_elements(p_hosts) as items(value)
  loop
    host_domain := item->>'domain';
    if host_domain is null or host_domain not in (
      'api.homesweethomegame.com',
      'hshsapi.homesweethomegame.com',
      'logapi.homesweethomegame.com',
      'boatltpk'
    ) then
      raise exception 'unsupported host domain';
    end if;
    if pg_catalog.jsonb_typeof(item->'enabled') <> 'boolean' then
      raise exception 'enabled must be a boolean';
    end if;

    purpose_value := pg_catalog.btrim(coalesce(item->>'purpose', ''));
    note_value := pg_catalog.btrim(coalesce(item->>'note', ''));
    if pg_catalog.char_length(purpose_value) > 120
       or pg_catalog.char_length(note_value) > 160 then
      raise exception 'purpose or note exceeds the allowed length';
    end if;

    update public.host_registry
       set enabled = (item->>'enabled')::boolean,
           purpose = purpose_value,
           note = note_value,
           updated_at = pg_catalog.now()
     where domain = host_domain;
    if not found then
      raise exception 'host registry row is missing: %', host_domain;
    end if;
  end loop;

  select coalesce(
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'domain', h.domain,
        'enabled', h.enabled,
        'purpose', h.purpose,
        'note', h.note,
        'updatedAt', h.updated_at
      )
      order by pg_catalog.array_position(
        array[
          'api.homesweethomegame.com',
          'hshsapi.homesweethomegame.com',
          'logapi.homesweethomegame.com',
          'boatltpk'
        ]::text[],
        h.domain
      )
    ),
    '[]'::jsonb
  )
  into after_state
  from public.host_registry as h;

  insert into public.host_registry_audit(actor, before_state, after_state)
  values ('admin', before_state, after_state);
  return after_state;
end;
$function$;

revoke all on function public.save_host_registry(jsonb) from public, anon, authenticated;
grant execute on function public.save_host_registry(jsonb) to service_role;


